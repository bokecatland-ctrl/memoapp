import { describe, expect, it } from 'vitest';
import { classify, detectDue } from './parse';

describe('classify', () => {
  it.each([
    ['やること、明日までにグラス発注', 'todo', '明日までにグラス発注'],
    ['やること明日までにグラス発注', 'todo', '明日までにグラス発注'], // 音声は句読点がないことが多い
    ['タスク グラス発注', 'todo', 'グラス発注'],
    ['アイデア、ティーペアリングのカード', 'idea', 'ティーペアリングのカード'],
    ['アイディア ティーのカード', 'idea', 'ティーのカード'],
    ['覚えておく、製氷機の点検は11/5午前', 'remember', '製氷機の点検は11/5午前'],
    ['覚えておくこと 製氷機の点検', 'remember', '製氷機の点検'],
    ['おぼえておく製氷機の点検', 'remember', '製氷機の点検'],
    ['メモ、改装打合せは火曜', 'remember', '改装打合せは火曜'],
    ['共有、朝食ラストオーダー変更', 'share', '朝食ラストオーダー変更'],
    ['伝える早番にラストオーダー変更', 'share', '早番にラストオーダー変更'],
    ['  やること:発注  ', 'todo', '発注'],
  ])('%s → %s', (text, category, body) => {
    expect(classify(text)).toEqual({ category, body });
  });

  it.each([
    'メモ帳を買う', // 区切りがないので「メモ」とはみなさない
    '共有スペースの掃除',
    'タスク管理の方法を考える',
    'ナプキンの在庫、来週分足りるか見る',
    'やること', // キーワードだけ
  ])('%s → 受信箱のまま', (text) => {
    expect(classify(text)).toEqual({ category: 'inbox', body: text });
  });
});

describe('detectDue', () => {
  const today = new Date(2026, 9, 30); // 2026-10-30(金)

  it.each([
    ['今日中にグラス見積もり', '2026-10-30'],
    ['明日までにグラス発注', '2026-10-31'],
    ['あしたの朝に確認', '2026-10-31'],
    ['明後日の会議まで', '2026-11-01'],
    ['あさって伝える', '2026-11-01'],
    ['11月5日に点検', '2026-11-05'],
    ['点検は11/5午前', '2026-11-05'],
    ['1月10日までに棚卸し', '2027-01-10'], // 過ぎた月は来年
    ['10月29日の件', '2026-10-29'], // 昨日なら今年(期限切れとして出す)
    ['5日までに提出', '2026-11-05'], // 今日より前の日は来月
    ['31日までに提出', '2026-10-31'],
    ['30日中に', '2026-10-30'],
    ['１１月７日まで', '2026-11-07'], // 全角
  ])('%s → %s', (text, due) => {
    expect(detectDue(text, today)).toBe(due);
  });

  it.each(['ティーペアリングのカード', '3日に1回確認する', '2月30日', '毎日チェック'])('%s → なし', (text) => {
    expect(detectDue(text, today)).toBeNull();
  });
});
